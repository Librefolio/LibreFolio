class FAEventUpsertPoint(FAAssetEventPoint):
    """Event point of a manual upsert, optionally naming the stored event it edits.

    - ``id`` set: the stored manual event with that id is edited in place. Every field
      may change, date and type included, and the id is kept, so a transaction linked
      to the event stays linked.
    - ``id`` unset, in an ``upsert`` item: the event replaces the stored manual events
      with the same ``(date, type)``. Those rows are updated in place and keep their
      ids; only events beyond the stored ones are inserted. In a ``create`` item, a
      ``(date, type)`` already stored is refused instead (``FAEventUpsert.mode``).

    ``from_attributes`` lets a plain ``FAAssetEventPoint`` instance stand for an
    upsert point without an id. Unknown fields are still rejected.
    """

    model_config = ConfigDict(from_attributes=True)

    id: Optional[int] = Field(None, description="Id of the stored manual event to edit in place; omit to match on (date, type) in an upsert item, or to add a new event in a create item")

    @field_validator("value")
    @classmethod
    def value_in_an_iso_currency(cls, value: Currency) -> Currency:
        """A manual event is written in an ISO 4217 alphabetic code, never a name or a number (E-18).

        Here, not on ``FAAssetEventPoint``: the providers build that one, and the events read back keep their stored code.
        """
        iso_currency_code(value.code)
        return value


class FAEventUpsert(StrictModel):
    """Manual event upsert for a single asset (multiple events).

    Groups multiple event points for one asset.
    Only for manual events (provider_assignment_id = NULL).

    ``mode`` (decision 20 of release 1.3):

    - ``"upsert"`` (default): an event without id updates the manual event with the same
      date and type in place — the event editor and its CSV import;
    - ``"create"``: «+ New event». An event on a date and type the asset already has,
      manual or from a provider, is refused (409 ``EVENT_EXISTS``, with the existing
      events), never overwritten. A create item names no event id.

    ``delete_ids`` (``upsert`` items only): events of the asset, manual or from a provider (one
    comes back with its next sync), deleted first, in the same transaction as the rest of the
    request, so an edit can take the date and type of an event deleted in the same save (the
    event editor's save, all or nothing: decision 22). An item may only delete; it needs at least
    one event or one id to delete.
    """

    asset_id: int = Field(..., description="Asset ID")
    mode: Literal["upsert", "create"] = Field(
        "upsert",
        description="upsert: an event without id updates the manual event with the same date and type. create: an event on a date and type the asset already has (manual or provider) is refused with 409 EVENT_EXISTS.",
    )
    events: List[FAEventUpsertPoint] = Field(default_factory=list, description="List of event points (empty when the item only deletes)")
    delete_ids: List[int] = Field(
        default_factory=list,
        description="upsert only: ids of events of this asset (manual, or from a provider: it comes back with its next sync) deleted first, in the same transaction. An id that is not an event of the asset is refused (400 EVENT_NOT_DELETABLE), an event linked to transactions too (409 EVENT_IN_USE).",
    )

    @model_validator(mode="after")
    def validate_item_not_empty(self) -> FAEventUpsert:
        if not self.events and not self.delete_ids:
            raise ValueError("An upsert item needs at least one event or one id to delete")
        return self

    @model_validator(mode="after")
    def validate_create_names_no_id(self) -> FAEventUpsert:
        if self.mode == "create" and any(event.id is not None for event in self.events):
            raise ValueError("A create item cannot name an event id: edit an event with mode 'upsert'")
        if self.mode == "create" and self.delete_ids:
            raise ValueError("A create item cannot delete events: delete them with mode 'upsert'")
        return self

    @model_validator(mode="after")
    def validate_delete_ids(self) -> FAEventUpsert:
        repeated = sorted({event_id for event_id in self.delete_ids if self.delete_ids.count(event_id) > 1})
        if repeated:
            raise ValueError(f"Duplicate id in delete_ids: {', '.join(str(event_id) for event_id in repeated)}")
        both = sorted(set(self.delete_ids) & {event.id for event in self.events if event.id is not None})
        if both:
            raise ValueError(f"An event cannot be deleted and edited in one item: {', '.join(str(event_id) for event_id in both)}")
        return self

    @model_validator(mode="after")
    def validate_unique_event_ids(self) -> FAEventUpsert:
        ids = [event.id for event in self.events if event.id is not None]
        repeated = sorted({event_id for event_id in ids if ids.count(event_id) > 1})
        if repeated:
            raise ValueError(f"Duplicate event id in one upsert item: {', '.join(str(event_id) for event_id in repeated)}")
        return self


class FAEventUpsertResult(StrictModel):
    """Result of event upsert for a single asset."""

    asset_id: int
    count: int
    message: str
    event_ids: List[int] = Field(default_factory=list, description="The id of the event each point of the item wrote, in request order")
    deleted_ids: List[int] = Field(default_factory=list, description="The ids of delete_ids, all deleted, in request order")


class FABulkEventUpsertResponse(BaseBulkResponse[FAEventUpsertResult]):
    """Response for bulk event upsert."""


class FAEventDeleteItemResult(StrictModel):
    """
    Per-item result of a bulk AssetEvent delete.

    status:
      - "deleted": event removed
      - "not_found": id did not match any event of the asset (an event of another
                     asset is left alone)
      - "in_use": event is referenced by one or more transactions (RESTRICT);
                  accessible_transactions[] lists tx IDs the caller can see,
                  hidden_transactions_count counts refs from other users.
    """

    event_id: int = Field(..., description="Event ID this result refers to")
    status: Literal["deleted", "not_found", "in_use"] = Field(..., description="Outcome for this event")
    accessible_transactions: List[int] = Field(
        default_factory=list,
        description="Transaction IDs referencing this event that the current user can access",
    )
    hidden_transactions_count: int = Field(
        default=0,
        description="Number of transactions referencing this event that belong to other users",
    )


class FAEventBulkDeleteResponse(StrictModel):
    """
    Aggregate response of a bulk AssetEvent delete.

    Always HTTP 200: inspect per-item ``results`` for per-id outcome.
    Successful deletions are committed even if others are blocked (no partial rollback).
    """

    results: List[FAEventDeleteItemResult] = Field(default_factory=list)
    deleted_count: int = Field(..., description="Count of events successfully deleted")
    not_found_count: int = Field(..., description="Count of ids that matched no event of the asset")
    in_use_count: int = Field(..., description="Count of events blocked by RESTRICT")


class FAEventQueryItem(StrictModel):
    """Single asset event query in a bulk request."""

    asset_id: int = Field(..., description="Asset ID to query")
    date_range: DateRangeModel = Field(..., description="Date range (end defaults to start)")
    target_currency: Optional[str] = Field(
        None,
        description=("Convert event.value to this currency via FX rates at each event's date (E.8). " "None = return events in their native currency. " "FX misses are surfaced as non-fatal warnings in FAEventQueryResult.errors."),
    )

    @field_validator("target_currency")
    @classmethod
    def target_currency_validate(cls, v: Optional[str]) -> Optional[str]:
        if v is not None:
            return Currency.validate_code(v)
        return v


class FAEventQueryResult(StrictModel):
    """Response for a single asset event query."""

    asset_id: int = Field(..., description="Asset ID queried")
    events: List[FAAssetEventPointOut] = Field(default_factory=list, description="Asset events with id and is_auto")
    errors: List[str] = Field(
        default_factory=list,
        description="Non-fatal warnings (e.g. FX rate missing for target_currency conversion at some event dates)",
    )


class FAEventQueryResponse(BaseListResponse[FAEventQueryResult]):
    """Bulk response for event queries."""
