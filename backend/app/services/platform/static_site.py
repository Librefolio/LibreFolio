"""The web app and the documentation, served by the backend after every API route.

Owner: workstream H (platform). Moved out of ``main.py`` as it was (CP2b), path confinement included.
``install_static_site(app)`` registers, in this order: ``/mkdocs`` and its files; ``/``, the web app or the API's name
when the app is not built; the build's chunks under ``/_app``, when the build exists; last, the SPA catch-all, which
must stay the last route of the app. The handlers read ``FRONTEND_BUILD_DIR`` and ``SITE_DIR`` when a request comes, so
a test can point them elsewhere.
"""

from pathlib import Path

from fastapi import FastAPI
from fastapi.responses import FileResponse, HTMLResponse
from fastapi.staticfiles import StaticFiles

from backend.app.config import API_V1_PREFIX, PROJECT_NAME, PROJECT_ROOT, get_version
from backend.app.utils.runtime.paths import confined_path

# Serve mkdocs site from FastAPI at /mkdocs if site directory exists, otherwise return placeholder HTML.
SITE_DIR = PROJECT_ROOT / "mkdocs_src" / "site"

# Frontend build directory (generated by `./dev.py front build`)
FRONTEND_BUILD_DIR = PROJECT_ROOT / "frontend" / "build"

# Every HTML document served from a build carries this. An HTML entry point names the hashed chunks of
# the CURRENT build: without it a browser reuses its cached copy (heuristic freshness from Last-Modified)
# and keeps running the build it had before an upgrade, with every immutable chunk that copy names, until
# a manual reload (beta report; issue #26, «Plugin does not work on chromium»). The chunks stay
# immutable: their names change with their content.
REVALIDATE_HTML = {"Cache-Control": "no-cache, must-revalidate"}


def _revalidated_file(path: Path) -> FileResponse:
    """A file of a build, told to revalidate when it is an HTML document."""
    return FileResponse(path, headers=REVALIDATE_HTML if path.suffix == ".html" else None)


def frontend_available() -> bool:
    """Check if frontend build exists and has index.html."""
    return FRONTEND_BUILD_DIR.exists() and (FRONTEND_BUILD_DIR / "index.html").exists()


def docs_available() -> bool:  # pragma: no cover
    return SITE_DIR.exists() and (SITE_DIR / "index.html").exists()


def render_docs_not_built() -> HTMLResponse:  # pragma: no cover
    return HTMLResponse("""<html><body>
        <h1>Documentation not generated</h1>
        <p>To build the <b>MkDocs</b> site, change into the <b>LibreFolio</b> installation directory and run:</p>
        <pre><code>cd `/path/to/LibreFolio`
./dev.py mkdocs build</code></pre>
        <p>If you are using <b>Docker</b> (coming soon), open a shell in the backend container and run the same command:</p>
        <pre><code>docker compose exec backend /bin/bash
./dev.py mkdocs build</code></pre>
        </body></html>""")


def mkdocs_root():  # pragma: no cover
    if docs_available():
        return _revalidated_file(SITE_DIR / "index.html")
    return render_docs_not_built()


def mkdocs_static(path: str):  # pragma: no cover
    if not docs_available():
        return render_docs_not_built()

    requested_path = path.strip("/")
    target = confined_path(SITE_DIR, requested_path)
    if target is None:
        return HTMLResponse("<h1>Documentation file not found</h1>", status_code=404)
    if target.is_dir():
        target = target / "index.html"

    if target.exists() and target.is_file():
        return _revalidated_file(target)

    return HTMLResponse("<h1>Documentation file not found</h1>", status_code=404)


async def root():  # pragma: no cover
    """
    Root endpoint.
    Serves frontend if build exists, otherwise provides API information.
    """
    if frontend_available():
        return _revalidated_file(FRONTEND_BUILD_DIR / "index.html")

    return {
        "name": PROJECT_NAME,
        "version": get_version(),
        "docs": f"{API_V1_PREFIX}/docs",
        "frontend": "Not built. Run: ./dev.py front build",
    }


# Mount _app directory for SvelteKit immutable assets (JS/CSS chunks).
# Content-hashed filenames → safe to cache hard for a year.
class ImmutableStaticFiles(StaticFiles):
    def file_response(self, *args, **kwargs):
        resp = super().file_response(*args, **kwargs)
        resp.headers.setdefault("Cache-Control", "public, max-age=31536000, immutable")
        return resp


# Catch-all for frontend routes (SPA support) - ALWAYS registered
# Checks at runtime if frontend exists
#
# IMPORTANT: This is a sync `def` (NOT `async def`) on purpose!
# FastAPI runs sync endpoints in a thread pool, so the blocking filesystem
# calls (Path.exists, Path.is_file, FileResponse) do NOT block the uvicorn
# event loop.
#
# NOTE: Direct /_app/... requests are handled by the StaticFiles mount
# (registered before this route, in install_static_site). This catch-all only handles:
# 1. Direct static files in build root (favicon, manifest, robots.txt, etc.)
# 2. SPA fallback (200.html for client-side routing)
def frontend_catchall(path: str):  # pragma: no cover
    """Serve frontend for any non-API route (SPA support)."""
    # Skip API and docs routes
    if path.startswith(("api/", "mkdocs")):
        return HTMLResponse("<h1>Not Found</h1>", status_code=404)

    # Check if frontend is available at runtime
    if not frontend_available():
        return HTMLResponse("<h1>Frontend not built</h1><p>Run: ./dev.py front build</p>", status_code=503)

    # Try to serve the exact file from the build directory
    # This handles: favicon.png, robots.txt, manifest, etc. — and index.html, 200.html, offline.html,
    # which revalidate like every HTML document of the build. A path that would leave the build
    # directory is never served: it falls through to the SPA fallback below.
    target = confined_path(FRONTEND_BUILD_DIR, path)
    if target is not None and target.exists() and target.is_file():
        return _revalidated_file(target)

    # For SPA routes, serve 200.html (fallback generated by adapter-static)
    # This contains the full SvelteKit app that can handle client-side routing.
    # Never cache it: it references the hashed chunks of the CURRENT build, so a
    # cached copy pins the user to an old bundle until a manual refresh (beta
    # report: version stayed on an old build until an explicit F5).
    fallback = FRONTEND_BUILD_DIR / "200.html"
    if fallback.exists():
        return _revalidated_file(fallback)

    # Fallback to index.html if 200.html doesn't exist
    return _revalidated_file(FRONTEND_BUILD_DIR / "index.html")


def install_static_site(app: FastAPI) -> None:
    """Register the documentation, the web app, its chunks and the SPA catch-all on ``app``, in this order."""
    app.get("/mkdocs", response_class=HTMLResponse)(mkdocs_root)
    app.get("/mkdocs/{path:path}")(mkdocs_static)
    app.get("/")(root)
    # Serve frontend static assets (JS, CSS, images) if build exists
    # This must be mounted AFTER all API routes to avoid conflicts, and before the catch-all
    #
    # PERFORMANCE: StaticFiles uses Starlette's async file serving (anyio),
    # which does NOT block the event loop. This is critical for serving 15+
    # JS chunks in parallel during SvelteKit page navigation.
    if frontend_available() and (FRONTEND_BUILD_DIR / "_app").exists():
        app.mount("/_app", ImmutableStaticFiles(directory=FRONTEND_BUILD_DIR / "_app"), name="frontend_app")
    app.get("/{path:path}")(frontend_catchall)
