<!--
  AssetCurrencyChangeModal.svelte — Confirm modal for a currency change (I.6 + R3-3 Policy D, N68).

  Opens from the asset modal when the user changes an asset's currency and the server's dry run
  (`currencyImpact.ts`, GET /assets/{id}/market-data/summary) says something would be lost. The change is never
  blocked: `PATCH /assets` deletes, in the same call, the asset's prices and every event that is not a SPLIT, and
  disconnects the transactions linked to a deleted event. The SPLIT events and the transactions linked to them stay.

  1. Show a summary of what is deleted / disconnected: N price points (oldest..newest), M manual events + K events
     generated by the provider, L transactions that lose their link to a deleted event (the transactions are kept),
     and the SPLIT events that stay.
  2. Offer export buttons (CSV / JSON) for prices and events so the user can keep a local snapshot first.
  3. On confirm:
     a. PATCH /assets                        (one call: changes the currency and deletes what goes).
     b. POST /assets/prices/sync             (if a provider is assigned and there were prices; repopulates the series
                                              in the new currency).
  The transactions that lost their link can be linked again from Transactions («Relink events»).

  Uses Svelte 5 runes.
-->
<script lang="ts">
    import {AlertTriangle, Download, X} from 'lucide-svelte';
    import {get} from 'svelte/store';
    import {zodiosApi} from '$lib/api';
    import {downloadAssetBackup, type BackupFormat, type BackupKind} from '$lib/api/backupDownload';
    import {toasts} from '$lib/stores/app/toastStore.svelte';
    import {_ as t} from '$lib/i18n';
    import {buildAssetSyncToast} from '$lib/utils/sync/syncToastHelpers';
    import {extractErrorMessage} from '$lib/utils/trySave';
    import type {CurrencyChangeImpact} from './currencyImpact';
    import InfoBanner from '$lib/components/ui/feedback/InfoBanner.svelte';
    import ModalBase from '$lib/components/ui/modals/ModalBase.svelte';

    interface Props {
        open: boolean;
        impact: CurrencyChangeImpact | null;
        patchPayload: Record<string, unknown> | null;
        providerAssigned: boolean;
        zIndex?: number;
        onconfirmed?: () => void;
        oncanceled?: () => void;
    }

    let {open = $bindable(), impact, patchPayload, providerAssigned, zIndex = 50, onconfirmed, oncanceled}: Props = $props();

    let inProgress = $state(false);
    /** Inline progress step (replaces the old toast chain, I-bis #12). */
    let progressStep: null | 'patch' | 'sync' = $state(null);

    /** Total events count (manual + provider) — convenient for the copy in the body. */
    const totalEvents = $derived(impact ? impact.eventsManual + impact.eventsProvider : 0);

    async function exportBackup(kind: BackupKind, format: BackupFormat) {
        if (!impact) return;
        // Uses the shared axiosInstance (cookie auth + 401 interceptor +
        // Accept-Language) instead of a raw ``window.open`` so every request
        // flows through the same pipeline as the rest of the Zodios client.
        // The backend picks the filename via ``Content-Disposition`` — we
        // just surface any HTTP error as a toast.
        try {
            await downloadAssetBackup(impact.assetId, kind, format);
        } catch (err: unknown) {
            // I-bis #22 — use centralised ``extractErrorMessage`` so FastAPI
            // ``detail`` (string / object / Pydantic array) surfaces uniformly.
            const detail = extractErrorMessage(err, 'unknown error');
            console.error(`[backup] ${kind}/${format}`, detail, err);
            toasts.error(`${$t('assetDetail.currencyChange.backupTitle')}: ${detail}`);
        }
    }

    async function handleConfirm() {
        if (!impact || !patchPayload) return;
        inProgress = true;
        progressStep = null;
        const tr = get(t);

        try {
            // Step 1: one PATCH — it changes the currency and deletes what goes (prices, non-SPLIT events, links).
            progressStep = 'patch';
            const patched = await zodiosApi.patch_assets_bulk_api_v1_assets_patch([patchPayload] as any);
            const patchResult = patched.results.find((result) => result.asset_id === impact.assetId);
            if (!patchResult?.success) throw new Error(patchResult?.message || tr('assetDetail.currencyChange.failed'));
            toasts.success(tr('assetDetail.currencyChange.changedTo', {values: {from: impact.from, to: impact.to}}));

            // Step 2: auto-sync (only if provider assigned AND we had prices to begin with).
            if (providerAssigned && impact.oldest) {
                progressStep = 'sync';
                const today = new Date().toISOString().slice(0, 10);
                try {
                    const syncResponse: any = await zodiosApi.sync_prices_bulk_api_v1_assets_prices_sync_post([
                        {
                            asset_id: impact.assetId,
                            date_range: {start: impact.oldest, end: today},
                        },
                    ]);
                    const r = syncResponse?.results?.[0];
                    if (r) {
                        const toast = buildAssetSyncToast(r, tr('common.sync'), tr);
                        toasts[toast.variant](toast.message);
                    } else {
                        toasts.error(`${tr('common.sync')} — ${tr('prices.sync.noResponse')}`);
                    }
                } catch (syncErr: unknown) {
                    // I-bis #22 — unified error extraction; the modal does
                    // NOT close on sync failure (the PATCH itself succeeded).
                    const detail = extractErrorMessage(syncErr, 'unknown error');
                    console.error('[currency-change] post-change auto-sync failed', detail, syncErr);
                    toasts.error(`${tr('common.sync')}: ${detail}`);
                }
            }

            open = false;
            onconfirmed?.();
        } catch (err: unknown) {
            // I-bis #22 — the PATCH failed: keep the modal open so the
            // user can retry or cancel; surface the detail via toast.
            const msg = extractErrorMessage(err, 'unknown error');
            console.error('[currency-change] flow failed', msg, err);
            toasts.error(`${$t('assetDetail.currencyChange.failed')}: ${msg}`);
        } finally {
            inProgress = false;
            progressStep = null;
        }
    }

    function handleCancel() {
        if (inProgress) return;
        open = false;
        oncanceled?.();
    }
</script>

{#if open && impact}
    <ModalBase {open} {zIndex} maxWidth="lg" closeOnBackdropClick={false} closeOnEscape={false} testId="currency-change-modal" labelledBy="currency-change-title" tone="danger">
        <!-- Header -->
        <div class="flex items-center gap-3 px-5 py-4 bg-lf-danger-soft border-b border-lf-danger-line">
            <AlertTriangle class="text-lf-danger flex-shrink-0" size={22} />
            <h2 id="currency-change-title" class="text-base font-semibold text-lf-danger-on-soft">
                {$t('assetDetail.currencyChange.title', {values: {from: impact.from, to: impact.to}})}
            </h2>
            <button type="button" class="ml-auto p-1 rounded text-lf-danger hover:bg-lf-danger-line transition-colors disabled:opacity-50" onclick={handleCancel} disabled={inProgress} aria-label={$t('common.cancel')} data-testid="currency-change-close-x">
                <X size={18} />
            </button>
        </div>

        <!-- Body -->
        <div class="px-5 py-4 space-y-4 text-sm overflow-y-auto">
            <p class="text-lf-secondary">
                {$t('assetDetail.currencyChange.bodyIntro')}
            </p>
            <p class="text-lf-danger font-medium">
                {$t('assetDetail.currencyChange.bodyCaveat')}
            </p>

            <!-- What is deleted / disconnected, and the splits that stay (R3-3 Policy D, N68) -->
            <ul class="text-xs text-lf-primary bg-lf-danger-soft/60 border border-lf-danger-line rounded-md p-3 space-y-1 list-disc list-inside">
                {#if impact.prices > 0}
                    <li data-testid="currency-change-summary-prices">{$t('assetDetail.currencyChange.summaryPrices', {values: {n: impact.prices, oldest: impact.oldest, newest: impact.newest}})}</li>
                {/if}
                {#if impact.eventsManual + impact.eventsProvider > 0}
                    <li data-testid="currency-change-summary-events">
                        {$t('assetDetail.currencyChange.summaryEvents', {
                            values: {manual: impact.eventsManual, provider: impact.eventsProvider},
                        })}
                    </li>
                {/if}
                {#if impact.linkedTx > 0}
                    <li class="font-medium text-lf-danger-on-soft" data-testid="currency-change-summary-linkedtx">
                        {$t('assetDetail.currencyChange.summaryLinkedTx', {values: {n: impact.linkedTx}})}
                    </li>
                {/if}
                {#if impact.splitsKept > 0}
                    <li data-testid="currency-change-summary-splits">{$t('assetDetail.currencyChange.summarySplitsKept', {values: {n: impact.splitsKept}})}</li>
                {/if}
            </ul>

            {#if providerAssigned && impact.oldest}
                <InfoBanner variant="info">
                    {$t('assetDetail.currencyChange.autoSyncInfo', {values: {from: impact.oldest}})}
                </InfoBanner>
            {:else if !providerAssigned}
                <InfoBanner variant="warning">
                    {$t('assetDetail.currencyChange.noProviderInfo')}
                </InfoBanner>
            {/if}

            <!-- Backup section — R3-3b: prices + events -->
            <div class="rounded-md border border-lf-subtle bg-lf-panel p-3">
                <div class="text-xs font-semibold text-lf-secondary mb-2">
                    {$t('assetDetail.currencyChange.backupTitle')}
                </div>
                <div class="flex gap-2 flex-wrap">
                    {#if impact.prices > 0}
                        <button
                            type="button"
                            class="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs bg-lf-card border border-lf-input rounded hover:bg-lf-neutral text-lf-secondary transition-colors"
                            onclick={() => exportBackup('prices', 'csv')}
                            disabled={inProgress}
                            data-testid="currency-change-export-prices-csv"
                        >
                            <Download size={13} />
                            {$t('assetDetail.currencyChange.exportPricesCsv')}
                        </button>
                        <button
                            type="button"
                            class="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs bg-lf-card border border-lf-input rounded hover:bg-lf-neutral text-lf-secondary transition-colors"
                            onclick={() => exportBackup('prices', 'json')}
                            disabled={inProgress}
                            data-testid="currency-change-export-prices-json"
                        >
                            <Download size={13} />
                            {$t('assetDetail.currencyChange.exportPricesJson')}
                        </button>
                    {/if}
                    {#if totalEvents > 0}
                        <button
                            type="button"
                            class="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs bg-lf-card border border-lf-input rounded hover:bg-lf-neutral text-lf-secondary transition-colors"
                            onclick={() => exportBackup('events', 'csv')}
                            disabled={inProgress}
                            data-testid="currency-change-export-events-csv"
                        >
                            <Download size={13} />
                            {$t('assetDetail.currencyChange.exportEventsCsv')}
                        </button>
                        <button
                            type="button"
                            class="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs bg-lf-card border border-lf-input rounded hover:bg-lf-neutral text-lf-secondary transition-colors"
                            onclick={() => exportBackup('events', 'json')}
                            disabled={inProgress}
                            data-testid="currency-change-export-events-json"
                        >
                            <Download size={13} />
                            {$t('assetDetail.currencyChange.exportEventsJson')}
                        </button>
                    {/if}
                </div>
            </div>
        </div>

        <!-- Footer -->
        <div class="flex justify-end gap-2 px-5 py-3 border-t border-lf-subtle bg-lf-panel">
            {#if inProgress && progressStep}
                <span class="mr-auto flex items-center gap-2 text-xs text-lf-secondary" data-testid="currency-change-progress-step" data-step={progressStep}>
                    <span class="inline-block h-3 w-3 rounded-full border-2 border-lf-muted border-t-transparent animate-spin"></span>
                    {#if progressStep === 'patch'}
                        {$t('assetDetail.currencyChange.progressPatch')}
                    {:else if progressStep === 'sync'}
                        {$t('assetDetail.currencyChange.progressSync', {values: {from: impact.oldest}})}
                    {/if}
                </span>
            {/if}
            <button type="button" class="px-4 py-2 text-sm bg-lf-neutral text-lf-secondary rounded hover:bg-lf-input/30 transition-colors disabled:opacity-50" onclick={handleCancel} disabled={inProgress} data-testid="currency-change-cancel">
                {$t('common.cancel')}
            </button>
            <button type="button" class="px-4 py-2 text-sm bg-lf-danger-solid hover:bg-lf-danger-hover text-lf-on-danger-solid rounded font-medium transition-colors disabled:opacity-50 disabled:cursor-not-allowed" onclick={handleConfirm} disabled={inProgress} data-testid="currency-change-confirm">
                {inProgress ? $t('assetDetail.currencyChange.working') : $t('assetDetail.currencyChange.confirm')}
            </button>
        </div>
    </ModalBase>
{/if}
