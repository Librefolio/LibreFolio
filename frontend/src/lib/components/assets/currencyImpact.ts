/**
 * What changing an asset's currency would delete, asked of the server before it is done (lot X5-3: N68).
 *
 * Changing the currency is never blocked. `PATCH /assets` deletes, in the same call, the asset's prices and every event that is
 * not a SPLIT, and disconnects the transactions linked to a deleted event; the SPLIT events, and the transactions linked to
 * them, stay. The asset modal tells the user how much goes before it sends the PATCH, from the dry run
 * `GET /assets/{id}/market-data/summary`, which writes nothing. This module asks, and decides whether there is anything to say;
 * the dialog itself is `AssetCurrencyChangeModal.svelte`.
 *
 * Unlike the dry run of a provider change (`providerImpact.ts`: advice, never a gate) this one is a gate: the PATCH deletes
 * data without any other check, so when the dry run fails the promise rejects and the save does not go on blind.
 *
 * @module components/assets/currencyImpact
 */

import {zodiosApi} from '$lib/api';

export interface CurrencyChangeImpact {
    assetId: number;
    from: string;
    to: string;
    /** Price points that go. */
    prices: number;
    /** Manual events that go (SPLITs not counted). */
    eventsManual: number;
    /** Events generated by the provider that go (SPLITs not counted). */
    eventsProvider: number;
    /** SPLIT events that stay, with the transactions linked to them: information, not a loss. */
    splitsKept: number;
    /** Transactions that lose the link to a deleted event (the transactions themselves are kept). */
    linkedTx: number;
    /** First and last day of the prices that go, empty when there are none. */
    oldest: string;
    newest: string;
}

function asRecord(value: unknown): Record<string, unknown> {
    return value && typeof value === 'object' && !Array.isArray(value) ? (value as Record<string, unknown>) : {};
}

/** A count from the server: a finite non-negative number, else 0. */
function count(value: unknown): number {
    const n = typeof value === 'number' ? value : NaN;
    return Number.isFinite(n) && n > 0 ? n : 0;
}

function day(value: unknown): string {
    return typeof value === 'string' ? value : '';
}

/** The dry run for one asset. Rejects with the request's own error when it fails. */
export async function loadCurrencyChangeImpact(assetId: number, from: string, to: string): Promise<CurrencyChangeImpact> {
    const answer = asRecord(await zodiosApi.market_data_summary_api_v1_assets__asset_id__market_data_summary_get({params: {asset_id: assetId}}));
    return {
        assetId,
        from,
        to,
        prices: count(answer.prices),
        eventsManual: count(answer.events_manual),
        eventsProvider: count(answer.events_provider),
        splitsKept: count(answer.splits_kept),
        linkedTx: count(answer.linked_tx),
        oldest: day(answer.oldest),
        newest: day(answer.newest),
    };
}

/** Whether the change deletes or disconnects anything: the kept splits alone are no reason to ask. */
export function hasSomethingToLose(impact: CurrencyChangeImpact): boolean {
    return impact.prices + impact.eventsManual + impact.eventsProvider + impact.linkedTx > 0;
}
