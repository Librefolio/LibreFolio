/**
 * allocationTypeEmoji — one explicit emoji per Type bucket (plan §4 row S4b, D11).
 *
 * The allocation engine groups holdings by their raw `asset_type` value, so any
 * `AssetType` value can reach the history chart's Type dimension, plus two synthetic
 * buckets: `Liquidity` (cash) and `Unknown` (an asset without a type). Nothing throws when
 * a value is missing from the table. The chart just draws the wrong glyph, or none. The
 * table this module replaced had ten keys and fell back to the ETF emoji, which drew
 * COMMODITY, REAL_ESTATE and Unknown as ETFs. This file is what catches that failure.
 *
 * WHERE THE TYPES COME FROM. `backend/app/db/models.py`, `class AssetType(StrEnum)`, by
 * regex. They are not taken from `$lib/utils/assetTypes` (`ASSET_TYPES`, `isEtfSubtype`):
 * those import `$lib/api/generated`, which is gitignored and regenerated by `api sync`, so a
 * test reading them stays green for whoever adds an enum value and forgets the sync.
 *
 * NO COUNTS. The enum is expected to grow. Every assertion is a loop over the scrape, and
 * each loop has an anti-vacuous guard in front of it: the scrape is non-empty and contains
 * values that are certainly present.
 *
 * Pure static analysis plus a pure function: no DOM, no store, no server. The environment
 * is `node` (see vitest.config.ts), so `fs` and `path` are native here.
 */
import {existsSync, readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {describe, expect, it} from 'vitest';

import {ASSET_TYPE_EMOJI, getAssetTypeEmoji} from './allocationTypeEmoji';

// -----------------------------------------------------------------------------
// COPIED from src/lib/utils/__tests__/assetTypeTables.test.ts (the path
// constants `HERE`, `FRONTEND_DIR`, `REPO_DIR` and `MODELS_PY`, and the helpers
// `read`, `assertScraped` and `readAssetTypes`), not imported: that file is K's
// enum gate, and importing a test file registers its tests twice.
// Only the relative depth of FRONTEND_DIR is this file's own.
