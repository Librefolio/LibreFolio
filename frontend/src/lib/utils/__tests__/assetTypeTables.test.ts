/**
 * The subtypes whose pastille does not follow D61, each with the decision that made it one.
 *
 * D61 draws the pastille of a subtype from the base type it contains, `PNG_MAP[primary(x)]`, and
 * has nothing to say only where that base type is the subtype itself. Adding a row here is the
 * only way to add an exception: without this table, a pastille that drifted from the rule and a
 * pastille that was told to differ would look exactly the same.
 */
const PASTILLE_EXCEPTIONS: Readonly<Record<string, {icon: string; decision: string}>> = {
    ETF_MONETARY: {icon: 'liquidity', decision: 'D67: a money-market fund contains no base type — cash is a balance, not an asset anyone buys — so it borrows the icon of the cash bucket'},
};

/**
 * R16 — the composite icons of the subtypes (T6).
 *
 * A subtype is drawn with the icon of its container, whole, and a pastille in the corner saying
 * what it contains (D52). The files are generated by `scripts/compose_asset_type_icons.py` from
 * the three tables scraped here, into the app and into the documentation; `PNG_MAP` must name
 * exactly the file the generator writes, or `getAssetTypeIconUrl()` asks for one that is not there.
 */
describe('composite icons of the subtypes (R16)', () => {
    it('names every subtype icon {container}-{content} and ships it to the app and to the docs', () => {
        const png = readRecord('PNG_MAP', ['STOCK', 'ETF', 'OTHER']);
        const {family} = readFamilies();
        const content = readRecord('ASSET_TYPE_CONTENT_ICON', FAMILY_ANCHORS);
        const misnamed: string[] = [];
        for (const [subtype, container] of family) {
            const composite = `${png.get(container)}-${content.get(subtype)}`;
            if (png.get(subtype) !== composite) misnamed.push(`${subtype}: PNG_MAP names '${png.get(subtype)}', the convention requires '${composite}'`);
        }

        expectNoGaps(
            misnamed,
            'PNG_MAP in src/lib/utils/assetTypes.ts does not name these subtypes after their composite, {PNG_MAP[container]}-{ASSET_TYPE_CONTENT_ICON[subtype]}. That is the file scripts/compose_asset_type_icons.py writes (and the script refuses to run while the names disagree), so the app would request a picture nobody generates.',
        );

        const missing: string[] = [];
        for (const directory of [ICON_DIR, DOCS_ICON_DIR]) {
            expect(existsSync(directory), `${path.relative(REPO_DIR, directory)} does not exist: the composite icons are generated into it, so a move must stop this gate rather than report every file as missing.`).toBe(true);
            for (const subtype of family.keys()) {
                const file = path.join(directory, `${png.get(subtype)}.png`);
                if (!existsSync(file)) missing.push(`${subtype} -> ${path.relative(REPO_DIR, file)}`);
            }
        }
        expectNoGaps(
            missing,
            'these composite icons are not on disk. In the app the <img> hides itself on error, so the subtype silently loses its picture; in the documentation the page shows a broken image. Regenerate them with scripts/compose_asset_type_icons.py (its --check mode compares the files on disk with a fresh build) and commit both copies.',
        );
    });

    it('fills every pastille with the icon of the base type the subtype contains (D61), save the declared exceptions (D67)', () => {
        const png = readRecord('PNG_MAP', ['STOCK', 'ETF', 'OTHER']);
        const {family} = readFamilies();
        const content = readRecord('ASSET_TYPE_CONTENT_ICON', FAMILY_ANCHORS);
        const primary = readRecord('PRIMARY_TYPE_MAP', ['ETF_STOCK', 'CROWDFUND_REAL_ESTATE']);
        const primaryOf = (type: string) => primary.get(type) ?? type;

        // An exception is admissible only where the rule is silent: a subtype that rolls up to itself.
        expectNoGaps(
            Object.keys(PASTILLE_EXCEPTIONS).filter((type) => !family.has(type) || primaryOf(type) !== type),
            'PASTILLE_EXCEPTIONS in this file declares exceptions that D61 does not need: these types are not subtypes, or they now roll up to a base type whose icon the rule can use. Drop the exception rather than keep a second rule for them.',
        );

        const offenders: string[] = [];
        for (const subtype of family.keys()) {
            const exception = PASTILLE_EXCEPTIONS[subtype];
            const expected = exception?.icon ?? png.get(primaryOf(subtype));
            if (content.get(subtype) === expected) continue;
            if (!exception && primaryOf(subtype) === subtype) offenders.push(`${subtype}: rolls up to itself, so D61 has no base type to draw — declare its pastille in PASTILLE_EXCEPTIONS, with the decision that chose it`);
            else offenders.push(`${subtype}: pastille '${content.get(subtype)}', expected '${expected}' (${exception ? exception.decision : `PNG_MAP[${primaryOf(subtype)}]`})`);
        }
        expectNoGaps(
            offenders,
            'ASSET_TYPE_CONTENT_ICON in src/lib/utils/assetTypes.ts draws these subtypes with a pastille that is not the icon of what they contain. The pastille says what the instrument holds — the same thing its badge colour says — so a pastille that disagrees with primaryAssetType() tells the user one thing in the corner and another in the badge.',
        );

        const unborrowable = Object.entries(PASTILLE_EXCEPTIONS)
            .filter(([, {icon}]) => !existsSync(path.join(ICON_DIR, `${icon}.png`)))
            .map(([type, {icon}]) => `${type} -> ${icon}.png`);
        expectNoGaps(unborrowable, 'the icons these exceptions borrow are not in frontend/static/icons/asset-types/: scripts/compose_asset_type_icons.py draws the pastille from that file and stops without it.');
    });
});

