function read(file: string): string {
    expect(existsSync(file), `${file} does not exist: this gate reads it as text, so a move or a rename must stop the suite rather than silently scrape nothing`).toBe(true);
    return readFileSync(file, 'utf-8');
}

/**
 * The anti-vacuous guard. Everything below loops over a scraped collection, so
 * an empty or mis-parsed scrape has to fail *here*, naming the source, instead
 * of turning the real assertions into no-ops that pass.
 */
function assertScraped(what: string, values: string[], anchors: string[]): void {
    expect(values.length, `${what}: the scrape returned nothing. The regex no longer matches the source — every assertion built on this list would pass without checking anything.`).toBeGreaterThan(0);
    const missingAnchors = anchors.filter((anchor) => !values.includes(anchor));
    expect(missingAnchors, `${what}: the scrape is missing values that are certainly present (${anchors.join(', ')}), so it parsed the file only partially and its result cannot be trusted.`).toEqual([]);
}

/** Extract a single `const NAME: Record<string, string> = { ... };` object literal. */
function scrapeRecordKeys(source: string, declaration: RegExp, what: string): string[] {
    const declarations = [...source.matchAll(new RegExp(declaration.source, 'g'))];
    expect(declarations.length, `${what}: expected exactly one declaration to scrape, found ${declarations.length}. An ambiguous or absent match means this gate is reading the wrong block.`).toBe(1);
    const start = declarations[0].index! + declarations[0][0].length;
    const end = source.indexOf('};', start);
    expect(end, `${what}: the object literal is never closed with "};" — the scrape has no boundary.`).toBeGreaterThan(start);
    return [...source.slice(start, end).matchAll(/^\s*([A-Z][A-Z0-9_]*)\s*:/gm)].map((match) => match[1]);
}

/**
 * The asset types, read from the Python enum. See the header for why this is not
 * taken from the generated Zod schemas.
 */
function readAssetTypes(): string[] {
    const source = read(MODELS_PY);
    const start = source.indexOf('class AssetType(StrEnum):');
    expect(start, 'backend/app/db/models.py no longer declares "class AssetType(StrEnum)": this gate cannot find the enum it is built on.').toBeGreaterThan(-1);
    const rest = source.slice(start);
    const nextClass = rest.search(/\nclass\s+\w+/);
    const body = nextClass === -1 ? rest : rest.slice(0, nextClass);
    return [...body.matchAll(/^ {4}[A-Z][A-Z0-9_]*\s*=\s*["']([A-Z0-9_]+)["']/gm)].map((match) => match[1]);
}

const ASSET_TYPES = readAssetTypes();

/** Report every gap at once: a red that names one type per run is a red read four times. */
function expectNoGaps(missing: string[], explanation: string): void {
    expect(missing, explanation).toEqual([]);
}

/**
 * The `KEY: 'value'` entries of one `const NAME: … = { … };` literal in assetTypes.ts.
 *
 * The declaration is matched the way `scripts/compose_asset_type_icons.py` matches it —
 * `export` optional, any type annotation — so the gate and the generator of the composite
 * icons read the same tables with the same eyes. Every key must carry a plain single-quoted
 * value: a key whose value the regex cannot read would otherwise drop out of every check
 * built on the table, silently, instead of failing one of them.
 */
function readRecord(name: string, anchors: string[]): Map<string, string> {
    const what = `${name} (src/lib/utils/assetTypes.ts)`;
    const source = read(ASSET_TYPES_TS);
    const declarations = [...source.matchAll(new RegExp(`(?:export\\s+)?const\\s+${name}\\s*:[^=]*=\\s*\\{`, 'g'))];
    expect(declarations.length, `${what}: expected exactly one declaration to scrape, found ${declarations.length}. An ambiguous or absent match means this gate is reading the wrong block.`).toBe(1);
    const start = declarations[0].index! + declarations[0][0].length;
    const end = source.indexOf('};', start);
    expect(end, `${what}: the object literal is never closed with "};" — the scrape has no boundary.`).toBeGreaterThan(start);
    const body = source.slice(start, end);
    const keys = [...body.matchAll(/^\s*([A-Z][A-Z0-9_]*)\s*:/gm)].map((match) => match[1]);
    assertScraped(what, keys, anchors);
    const entries = [...body.matchAll(/^\s*([A-Z][A-Z0-9_]*)\s*:\s*'([^']*)'/gm)].map((match) => [match[1], match[2]] as const);
    expect(
        entries.map(([key]) => key),
        `${what}: some entries are not plain single-quoted strings, so their values cannot be read as text and would drop out of every check built on this table.`,
    ).toEqual(keys);
    expect(new Set(keys).size, `${what}: a key is declared twice. JavaScript keeps the last one without a word, so the table does not do what it reads as.`).toBe(keys.length);
    return new Map(entries);
}

/**
 * The screen order of the type select, read as text. It is never imported, for the reason
 * given in the creation-menu test below: on a checkout without `generated.ts` an import
 * would compare an empty list to an empty list and report success.
 */
function readMenuOrder(): string[] {
    const source = read(ASSET_TYPES_TS);
    const declarations = [...source.matchAll(/export const ASSET_TYPE_MENU_ORDER\s*:\s*readonly string\[\]\s*=\s*\[/g)];
    expect(declarations.length, `assetTypes.ts: expected exactly one ASSET_TYPE_MENU_ORDER declaration to scrape, found ${declarations.length}.`).toBe(1);
    const start = declarations[0].index! + declarations[0][0].length;
    const end = source.indexOf('];', start);
    expect(end, 'assetTypes.ts: the ASSET_TYPE_MENU_ORDER array is never closed with "];".').toBeGreaterThan(start);
    const menu = [...source.slice(start, end).matchAll(/'([A-Z][A-Z0-9_]*)'/g)].map((match) => match[1]);
    assertScraped('ASSET_TYPE_MENU_ORDER (src/lib/utils/assetTypes.ts)', menu, ['STOCK', 'ETF', 'OTHER']);
    return menu;
}

/**
 * First and last entry of the ETF block, and the crowdfunding one: a scrape that holds all
 * three crossed the whole literal rather than stopping at a line it could not parse.
 */
const FAMILY_ANCHORS = ['ETF_STOCK', 'ETF_MONETARY', 'CROWDFUND_REAL_ESTATE'];

/** `ASSET_TYPE_FAMILY` (subtype → container) and the containers it names, both guarded. */
function readFamilies(): {family: Map<string, string>; containers: string[]} {
    const family = readRecord('ASSET_TYPE_FAMILY', FAMILY_ANCHORS);
    const containers = [...new Set(family.values())];
    assertScraped('family containers (the values of ASSET_TYPE_FAMILY)', containers, ['ETF', 'CROWDFUND']);
    return {family, containers};
}

